// Reproducible, text-free derivatives of the existing reviewed paintings.
// Run from mobile: node scripts/build-widget-heritage.mjs (ImageMagick 6).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'assets/widget-backgrounds');
const sources = {
  prayer: ['category-granth-open-scripture.webp', 0.5], vishnu: ['source-vishnu-narayana.webp', 0.28],
  krishna: ['deity-krishna-bansuri.webp', 0.5], shiva: ['shiva.webp', 0.43], hanuman: ['ram-hanuman.webp', 0.42],
  rama: ['deity-rama-darbar.webp', 0.5], ganesha: ['deity-ganesha-modak.webp', 0.5], durga: ['deity-durga-lion.webp', 0.5],
  saraswati: ['deity-saraswati-veena.webp', 0.5], surya: ['deity-surya.webp', 0.5], panchang: ['panchang-celestial-almanac.webp', 0.5],
};
const sizes = { small: [256, 256], medium: [560, 260], large: [560, 560] };
const modes = { day: { paper: '#F8EFD6', gold: '#B79755' }, night: { paper: '#091A32', gold: '#8B743F' } };
const manifest = { generator: 'scripts/build-widget-heritage.mjs', sources: {}, assets: {} };
const hash = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');
const run = (args, options = {}) => execFileSync('convert', args, { maxBuffer: 8 * 1024 * 1024, ...options });
fs.mkdirSync(out, { recursive: true });
const entries = [];
for (const [subject, [file, focus]] of Object.entries(sources)) {
  const source = path.join(root, 'assets/reader-illustrations', file);
  manifest.sources[subject] = { file: `assets/reader-illustrations/${file}`, sha256: hash(fs.readFileSync(source)), focusX: focus };
  for (const [size, [w, h]] of Object.entries(sizes)) for (const [mode, colors] of Object.entries(modes)) {
    const panchang = subject === 'panchang';
    const aw = Math.round(w * (panchang ? 0.19 : 0.29));
    const ah = panchang ? aw : h - 12;
    const x = w - aw - 8; const y = panchang ? 12 : 6;
    // A portrait crop for deity busts; the almanac is a decorative solar cameo,
    // never an asserted lunar phase. Keep paint outside every text-safe region.
    const [sw, sh] = execFileSync('identify', ['-format', '%w %h', source], { encoding: 'utf8' }).trim().split(' ').map(Number);
    const cw = Math.min(sw, Math.round(sh * aw / ah)); const ch = Math.min(sh, Math.round(sw * ah / aw));
    const cx = Math.max(0, Math.min(sw - cw, Math.round(sw * focus - cw / 2)));
    const cy = Math.max(0, Math.round((sh - ch) / 2));
    const art = run([source, '-crop', `${cw}x${ch}+${cx}+${cy}`, '+repage', '-resize', `${aw}x${ah}!`, '-strip', 'png:-']);
    // No SVG delegate needed: use ImageMagick's built-in drawing primitives.
    const maskBytes = run(['-size', `${ah}x${aw}`, 'gradient:black-white', '-rotate', '-90', '-level', '0%,23%', 'png:-']);
    const tmp = path.join(out, '.heritage-art.png'); const maskFile = path.join(out, '.heritage-mask.png');
    fs.writeFileSync(tmp, art); fs.writeFileSync(maskFile, maskBytes);
    const bytes = run(['-size', `${w}x${h}`, `xc:${colors.paper}`, '-fill', 'none', '-stroke', colors.gold, '-strokewidth', '1', '-draw', `roundrectangle 3,3 ${w-4},${h-4} 26,26`, '(', tmp, maskFile, '-alpha', 'off', '-compose', 'CopyOpacity', '-composite', ')', '-geometry', `+${x}+${y}`, '-compose', 'Over', '-composite', '-strip', '-sampling-factor', '4:2:0', '-quality', '86', 'jpg:-']);
    fs.rmSync(tmp); fs.rmSync(maskFile);
    const name = `vedansh_widget_bg_heritage_${subject}_${size}_${mode}`;
    fs.writeFileSync(path.join(out, `${name}.jpg`), bytes);
    manifest.assets[name] = { width: w, height: h, bytes: bytes.length, sha256: hash(bytes), subject, appearance: mode, textSafeRight: panchang ? 0.73 : 0.69 };
    entries.push(`  ${name}: require('./${name}.jpg'),`);
  }
}
fs.writeFileSync(path.join(out, 'heritage.ts'), `// Generated by scripts/build-widget-heritage.mjs\nexport const widgetHeritageImages: Record<string, number> = {\n${entries.join('\n')}\n};\n`);
fs.writeFileSync(path.join(out, 'heritage-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Generated ${entries.length} budgeted Heritage/Midnight plates.`);
