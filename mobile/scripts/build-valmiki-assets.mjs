#!/usr/bin/env node
/**
 * Publish the Valmiki Ramayan corpus as bundled ASSET files instead of JS.
 *
 *   node scripts/build-valmiki-assets.mjs           # (re)write the parts
 *   node scripts/build-valmiki-assets.mjs --check   # exit 1 if they are stale
 *
 * WHY. The seven `src/data/valmiki-ramayan/chapter-0N.json` masters are 27 MB.
 * While the app `require()`d them they were compiled into the Hermes bundle:
 * more than half of it, re-downloaded in full by every OTA update, for a text
 * most sessions never open. As assets they are stored once (in the store
 * binary), addressed by content hash, and an OTA carries only the ones whose
 * bytes changed — normally none.
 *
 * WHAT IT WRITES.
 *   assets/valmiki-ramayan/k<N>_p<MM>.txt   the verses, as a JSON array, in
 *                                            reading order, split into parts
 *   src/data/valmiki-ramayan/parts.ts       the part table (asset handles +
 *                                            verse ranges), loaded lazily
 *   src/data/valmiki-ramayan/sarga-starts.json   first verse index of every
 *                                            sarga, so a "kāṇḍa.sarga" link can
 *                                            be opened without loading a kāṇḍa
 *
 * The masters stay where they are and remain the source of truth: provenance,
 * the corpus tests and `scripts/build-valmiki-ramayan.py` all still read them.
 * The app must never import them again (`valmikiAssets.test.ts` enforces it).
 *
 * The parts are plain JSON text with a `.txt` extension because Metro only
 * treats a file as an asset by extension, and `.json` is a source extension.
 * Part names use `_` only: Android derives a resource name by deleting every
 * character outside [a-z0-9_], so `k1-p01` and `k1p-01` would collide.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MASTERS = path.join(ROOT, 'src/data/valmiki-ramayan');
const ASSETS = path.join(ROOT, 'assets/valmiki-ramayan');
const PARTS_TS = path.join(MASTERS, 'parts.ts');
const SARGA_STARTS = path.join(MASTERS, 'sarga-starts.json');

/**
 * A part is closed once it reaches this many bytes. Small enough that parsing
 * one never holds the JS thread for long on a slow phone; large enough that a
 * kāṇḍa is a dozen-odd files rather than hundreds.
 */
const PART_BYTES = 384 * 1024;

function build() {
  const manifest = JSON.parse(fs.readFileSync(path.join(MASTERS, 'chapters-manifest.json'), 'utf8'));
  /** @type {Map<string, string>} file name → contents */
  const files = new Map();
  const table = [];
  const sargaStarts = {};

  for (const summary of manifest) {
    const kanda = summary.chapter;
    const master = JSON.parse(
      fs.readFileSync(path.join(MASTERS, `chapter-${String(kanda).padStart(2, '0')}.json`), 'utf8'),
    );
    if (master.verses.length !== summary.verseCount) {
      throw new Error(`kāṇḍa ${kanda}: master has ${master.verses.length} verses, manifest says ${summary.verseCount}`);
    }

    // The same predicate the reader link used against the loaded kāṇḍa:
    // the first verse whose reference begins `kāṇḍa.sarga.`.
    const starts = new Array(summary.sargaCount).fill(-1);
    master.verses.forEach((verse, index) => {
      for (let sarga = 1; sarga <= summary.sargaCount; sarga += 1) {
        if (starts[sarga - 1] === -1 && verse.reference.startsWith(`${kanda}.${sarga}.`)) starts[sarga - 1] = index;
      }
    });
    sargaStarts[kanda] = starts;

    const parts = [];
    let pending = [];
    let pendingBytes = 0;
    let firstVerse = 0;
    const close = () => {
      if (pending.length === 0) return;
      const name = `k${kanda}_p${String(parts.length + 1).padStart(2, '0')}.txt`;
      files.set(name, `${JSON.stringify(pending)}\n`);
      parts.push({ name, firstVerse, verseCount: pending.length });
      firstVerse += pending.length;
      pending = [];
      pendingBytes = 0;
    };
    for (const verse of master.verses) {
      pending.push(verse);
      pendingBytes += Buffer.byteLength(JSON.stringify(verse), 'utf8') + 1;
      if (pendingBytes >= PART_BYTES) close();
    }
    close();
    table.push(parts);
  }

  const lines = [
    '// GENERATED by scripts/build-valmiki-assets.mjs — do not edit by hand.',
    '//',
    '// Each `require` is a bundled ASSET handle, not the text: nothing here puts',
    '// a verse in the JS bundle. Reached only through a lazy `require()` in',
    '// `index.ts`, so the handles are not even registered until a kāṇḍa opens.',
    '',
    'export type ValmikiPart = {',
    '  /** Metro asset handle for the part file. */',
    '  source: number;',
    '  /** Index, within the kāṇḍa, of this part\'s first verse. */',
    '  firstVerse: number;',
    '  verseCount: number;',
    '};',
    '',
    '/** `valmikiParts[kāṇḍa - 1]` — that kāṇḍa\'s parts, in reading order. */',
    'export const valmikiParts: readonly (readonly ValmikiPart[])[] = [',
  ];
  for (const parts of table) {
    lines.push('  [');
    for (const part of parts) {
      lines.push(
        `    { source: require('@assets/valmiki-ramayan/${part.name}') as number, firstVerse: ${part.firstVerse}, verseCount: ${part.verseCount} },`,
      );
    }
    lines.push('  ],');
  }
  lines.push('];', '');

  return {
    files,
    partsTs: lines.join('\n'),
    sargaStarts: `${JSON.stringify(sargaStarts)}\n`,
  };
}

function current() {
  const files = new Map();
  if (fs.existsSync(ASSETS)) {
    for (const name of fs.readdirSync(ASSETS)) {
      if (name.endsWith('.txt')) files.set(name, fs.readFileSync(path.join(ASSETS, name), 'utf8'));
    }
  }
  const read = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null);
  return { files, partsTs: read(PARTS_TS), sargaStarts: read(SARGA_STARTS) };
}

const next = build();

if (process.argv.includes('--check')) {
  const now = current();
  const problems = [];
  for (const [name, contents] of next.files) {
    if (now.files.get(name) !== contents) problems.push(`assets/valmiki-ramayan/${name} is missing or stale`);
  }
  for (const name of now.files.keys()) {
    if (!next.files.has(name)) problems.push(`assets/valmiki-ramayan/${name} is no longer produced`);
  }
  if (now.partsTs !== next.partsTs) problems.push('src/data/valmiki-ramayan/parts.ts is stale');
  if (now.sargaStarts !== next.sargaStarts) problems.push('src/data/valmiki-ramayan/sarga-starts.json is stale');
  if (problems.length > 0) {
    console.error(problems.join('\n'));
    console.error('\nRun: node scripts/build-valmiki-assets.mjs');
    process.exit(1);
  }
  console.log(`valmiki assets are in sync (${next.files.size} parts)`);
} else {
  fs.mkdirSync(ASSETS, { recursive: true });
  for (const name of fs.readdirSync(ASSETS)) {
    if (name.endsWith('.txt') && !next.files.has(name)) fs.rmSync(path.join(ASSETS, name));
  }
  let bytes = 0;
  for (const [name, contents] of next.files) {
    fs.writeFileSync(path.join(ASSETS, name), contents);
    bytes += Buffer.byteLength(contents, 'utf8');
  }
  fs.writeFileSync(PARTS_TS, next.partsTs);
  fs.writeFileSync(SARGA_STARTS, next.sargaStarts);
  console.log(`wrote ${next.files.size} parts, ${(bytes / 1e6).toFixed(1)} MB`);
}
