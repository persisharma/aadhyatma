// Generate native navigation checks from independent authoring chapter files.
// Run from mobile/: node scripts/generate-library-boundaries.mjs
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const quote=value=>JSON.stringify(value);
const steps=[];
const add=(key,value)=>steps.push(`- ${key}: ${quote(value)}`);
const wait=value=>steps.push(`- extendedWaitUntil:\n    visible: ${quote(value)}\n    timeout: 20000`);
steps.push('- runFlow: _launch.yaml', '- tapOn: { id: "tab-more" }', '- scrollUntilVisible:\n    element:\n      text: "Language,.*"\n    centerElement: true');
add('tapOn','Language,.*');add('tapOn','English');steps.push('- tapOn: { id: "tab-home" }');
add('tapOn','Search verses, sections, and mantras');
for(const family of ['gita','valmiki-ramayan']) {
 const files=fs.readdirSync(path.join(root,'src/data',family)).filter(p=>/^chapter-\d+\.json$/.test(p)).sort();
 const chapters=files.map(file=>JSON.parse(fs.readFileSync(path.join(root,'src/data',family,file),'utf8')));
 for(let i=0;i<chapters.length;i++) {
  const chapter=chapters[i], last=chapter.verses.at(-1), next=chapters[i+1]?.verses[0];
  const gita=family==='gita';
  const label=gita ? `Verse ${last.chapter}.${last.number}` : last.labelEn;
  const query=gita ? label : last.reference;
  const source=gita ? 'Bhagavad Gītā' : 'Valmiki Ramayan';
  const escape=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
  const body=v=>gita ? `Verse ${v.chapter}\\.${v.number}\\..*` : `${escape(v.labelEn)}\\..*`;
  steps.push(`# ${family} chapter ${chapter.chapter}: final verse, forward transition, backward transition`);
  add('tapOn','Search input');steps.push('- eraseText: 256');add('inputText',query);
  wait(`Open ${escape(source)} ${escape(label)}`);add('tapOn',`Open ${escape(source)} ${escape(label)}`);
  wait(body(last));steps.push('- swipe: { direction: LEFT }');
  if(next) {
   wait(body(next));steps.push('- swipe: { direction: RIGHT }');wait(body(last));
  } else { steps.push('- waitForAnimationToEnd');add('assertVisible',body(last)); }
  add('tapOn','Back to chapters');wait('Search input');
 }
}
steps.push('- stopApp');
fs.writeFileSync(path.join(root,'.maestro/sqlite-chapter-boundaries.yaml'),
 '# Generated by scripts/generate-library-boundaries.mjs; all Gita/Ramayan chapter edges.\nappId: com.prashantsharma.vedansh\n---\n'+steps.join('\n')+'\n');
console.log('Generated 18 Gita and 7 Valmiki chapter boundary journeys');
