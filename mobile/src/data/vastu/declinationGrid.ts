const nodeAt = (latIndex: number, lonIndex: number): number =>
  DECLINATION_GRID_TENTHS[latIndex * GRID_COLS + lonIndex];

/**
 * Bilinear interpolation over the grid, in degrees (east-positive). Null for
 * coordinates outside 6–38°N / 66–100°E — the caller stays magnetic.
 */
export function getDeclinationForCoords(latitude: number, longitude: number): number | null {
  if (
    !Number.isFinite(latitude) ||
    !Number.isFinite(longitude) ||
    latitude < GRID_LAT_MIN ||
    latitude > GRID_LAT_MAX ||
    longitude < GRID_LON_MIN ||
    longitude > GRID_LON_MAX
  ) {
    return null;
  }
  const y = latitude - GRID_LAT_MIN;
  const x = longitude - GRID_LON_MIN;
  // Clamp the cell base so the box's far edges interpolate inside the last cell.
  const y0 = Math.min(Math.floor(y), GRID_ROWS - 2);
  const x0 = Math.min(Math.floor(x), GRID_COLS - 2);
  const fy = y - y0;
  const fx = x - x0;
  const top = nodeAt(y0, x0) * (1 - fx) + nodeAt(y0, x0 + 1) * fx;
  const bottom = nodeAt(y0 + 1, x0) * (1 - fx) + nodeAt(y0 + 1, x0 + 1) * fx;
  return (top * (1 - fy) + bottom * fy) / 10;
}
